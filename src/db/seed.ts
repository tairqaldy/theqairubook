/** Inserts a friendship unless one exists in either direction. */
async function befriend(fromId: number, toId: number, status: "accepted" | "pending", h: number) {
  const [exists] = await db
    .select({ id: friendships.id })
    .from(friendships)
    .where(
      or(
        and(eq(friendships.fromUserId, fromId), eq(friendships.toUserId, toId)),
        and(eq(friendships.fromUserId, toId), eq(friendships.toUserId, fromId))
      )
    )
    .limit(1);
  if (exists) return;
  await db.insert(friendships).values({ fromUserId: fromId, toUserId: toId, status, createdAt: hoursAgo(h) });
  if (status === "accepted") {
    await db.insert(boardEvents).values({
      actorUserId: fromId,
      targetUserId: toId,
      kind: "friend",
      detail: "became friends",
      createdAt: hoursAgo(h),
    });
  }
}

