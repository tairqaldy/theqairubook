async function count(table: typeof users | typeof discussionPosts | typeof discussionComments | typeof media | typeof votes | typeof friendships | typeof messages | typeof wallPosts | typeof repEvents) {
  const [row] = await db.select({ n: sql<number>`count(*)::int` }).from(table);
  return row.n;
}

